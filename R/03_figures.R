df <- readRDS("output/oregon_counties.rds")
labels <- c(trump_per_100pop="Trump votes per 100 residents", log_crime="Log offenses per 100,000",
            log_density="Log people per square mile", income="Per-capita income (USD)")
write.csv(sapply(df[c(names(labels),"density","crime_per_100k")],summary), "output/summary_statistics.csv")
write.csv(cor(df[names(labels)]), "output/correlations.csv")
pdf("output/paper_figures.pdf", width=8, height=7, useDingbats=FALSE)
par(mfrow=c(2,2))
for(k in names(labels)) hist(df[[k]], main=labels[[k]], xlab=labels[[k]], col="lightblue", border="white")
par(mfrow=c(1,1))
pairs(df[names(labels)], labels=c("Votes per 100","Log crime","Log density","Income"), pch=19)
for(k in c("log_crime","log_density")) {
  plot(df[[k]],df$trump_per_100pop,xlab=labels[[k]],ylab=labels[[1]],pch=19)
  abline(lm(df$trump_per_100pop ~ df[[k]]),col="#AD5032",lwd=2)
}
m <- lm(trump_per_100pop ~ log_crime * log_density + income, df)
x <- seq(min(df$log_crime),max(df$log_crime), length.out=100)
levels_d <- quantile(df$log_density,c(.25,.50,.75))
pred <- sapply(levels_d,function(d) predict(m,data.frame(log_crime=x,log_density=d,income=mean(df$income))))
matplot(x,pred,type="l",lty=1:3,lwd=2,col=1:3,xlab=labels[["log_crime"]],ylab="Predicted Trump votes per 100 residents")
legend("topright",paste(names(levels_d),"density"),lty=1:3,col=1:3,bty="n")
par(mfrow=c(2,2))
plot(m,which=c(1,2,4,5))
dev.off()
png("output/crime_vs_vote.png", width=900,height=650)
colors <- hcl.colors(24,"Viridis")
plot(df$log_crime,df$trump_per_100pop,pch=19,col=colors[cut(df$log_density,24,labels=FALSE)],
     xlab=labels[["log_crime"]],ylab=labels[[1]],main="Oregon counties, 2024")
abline(lm(trump_per_100pop ~ log_crime,df),col="grey30")
legend("topright",c("Low density","High density"),col=colors[c(1,24)],pch=19,bty="n")
dev.off()
